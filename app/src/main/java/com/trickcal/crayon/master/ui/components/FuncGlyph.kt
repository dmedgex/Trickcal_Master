/**
 * 首页功能图标：轮廓取自设计参考图（提取白色主体 -> 简化 -> 归一化 100x100），
 * 形状与原图一致，矢量绘制，任意分辨率清晰。
 */
enum class FuncGlyph { PAW, CRAYONS, CHIBI, KEY_SWORD }

@Composable
fun FuncGlyphIcon(kind: FuncGlyph, tint: Color, modifier: Modifier = Modifier) {
    Canvas(modifier = modifier) {
        val s = size.minDimension / 100f
        val contours = when (kind) {
            FuncGlyph.PAW -> PAW_CONTOURS
            FuncGlyph.CRAYONS -> CRAYON_CONTOURS
            FuncGlyph.CHIBI -> CHIBI_CONTOURS
            FuncGlyph.KEY_SWORD -> KEY_SWORD_CONTOURS
        }
        drawPath(contours.toPath(s), tint)
    }
}

private fun List<FloatArray>.toPath(s: Float): Path = Path().apply {
    fillType = PathFillType.EvenOdd
    forEach { pts ->
        moveTo(pts[0] * s, pts[1] * s)
        var i = 2
        while (i + 1 < pts.size) {
            lineTo(pts[i] * s, pts[i + 1] * s)
            i += 2
        }
        close()
    }
}

